function normalizeSearch(value: string): string {
  return value
    .trim()
    .replace(/[\u0591-\u05C7]/g, '')
    .replace(/['"״׳-]/g, ' ')
    .replace(/יי/g, 'י')
    .replace(/וו/g, 'ו')
    .replace(/\s+/g, ' ');
}

export function filterIsraelCities(query: string): CitySchedule[] {
  const normalized = normalizeSearch(query);
  if (!normalized) {
    return ISRAEL_CITY_SCHEDULES;
  }

  const tokens = normalized.split(' ').filter(Boolean);
  return ISRAEL_CITY_SCHEDULES.filter((city) => {
    const haystack = normalizeSearch(`${city.name} ${city.region}`);
    return tokens.every((token) => haystack.includes(token));
  });
}
